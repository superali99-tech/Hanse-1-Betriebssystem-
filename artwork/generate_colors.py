#!/usr/bin/env python3
"""Derive the NovaLight / NovaDark Plasma colour schemes from KDE Breeze.

Breeze colour schemes are LGPL-2.0-or-later (KDE). NovaOS replaces Breeze's
blue accent with the Nova violet and gives the neutral surfaces a slightly
cooler tint. Usage:
    python3 artwork/generate_colors.py /usr/share/color-schemes OUTDIR
"""
import os
import sys

SRC, OUT = sys.argv[1], sys.argv[2]

COMMON = {
    "61,174,233": "124,92,255",     # accent / focus / hover
    "163,212,250": "196,184,255",   # selection alternate
    "41,128,185": "91,76,230",      # links (light)
    "29,153,243": "157,134,255",    # links (dark)
    "26,83,113": "62,46,128",       # dark selection alternate
}
LIGHT = {
    "239,240,241": "242,243,249",   # window
    "227,229,231": "232,234,244",   # window alternate / header inactive
    "222,224,226": "228,231,242",   # header
    "247,247,247": "248,248,252",
}
DARK = {
    "32,35,38": "26,29,42",         # window
    "41,44,48": "33,37,53",         # header
    "20,22,24": "20,23,35",         # view
    "29,31,34": "24,27,40",
    "41,44,48": "33,37,53",
    "49,54,59": "40,44,62",         # button
}


def convert(name, new_id, new_name, mapping):
    with open(os.path.join(SRC, name), encoding="utf-8") as fh:
        text = fh.read()
    out = []
    for line in text.splitlines():
        if line.startswith("Name[") or line.startswith("# SPDX-FileCopyrightText"):
            continue
        if line.startswith("ColorScheme="):
            line = f"ColorScheme={new_id}"
        elif line.startswith("Name="):
            line = f"Name={new_name}"
        elif "=" in line:
            key, val = line.split("=", 1)
            for a, b in {**COMMON, **mapping}.items():
                if val == a:
                    val = b
            line = f"{key}={val}"
        out.append(line)
    header = ("# NovaOS colour scheme, derived from KDE Breeze (LGPL-2.0-or-later).\n"
              "# Generated by artwork/generate_colors.py\n")
    with open(os.path.join(OUT, new_id + ".colors"), "w", encoding="utf-8") as fh:
        fh.write(header + "\n".join(out).lstrip("\n") + "\n")


os.makedirs(OUT, exist_ok=True)
convert("BreezeLight.colors", "NovaLight", "Nova Light", LIGHT)
convert("BreezeDark.colors", "NovaDark", "Nova Dark", DARK)
print("written NovaLight.colors and NovaDark.colors to", OUT)
