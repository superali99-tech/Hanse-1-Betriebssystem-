#!/usr/bin/env python3
"""Soundtrack for the NovaOS trailer - synthesized from scratch (no samples).

120 s, 96 BPM (one bar = 2.5 s, 48 bars), D major, progression
Dmaj9 - Bm9 - Gmaj9 - Asus4 (two bars each). Layers: warm pad, plucked
arpeggio, sub bass, soft kick + hat in the middle part, synthetic reverb.
Being generated by this script, the music is free of third-party rights.

    python3 music.py out.wav            (needs numpy)
"""
import sys
import wave

import numpy as np

SR = 48000
BPM = 96
BEAT = 60 / BPM          # 0.625 s
BAR = 4 * BEAT           # 2.5 s
LENGTH = 120.0
N = int(SR * LENGTH)
t_all = np.arange(N) / SR
rng = np.random.default_rng(7)


def midi(n):
    return 440.0 * 2 ** ((n - 69) / 12)


# chord tones (MIDI): pad voicing, arpeggio notes, bass root
CHORDS = [
    ([50, 57, 61, 64, 66], [62, 66, 69, 73, 76, 73, 69, 66], 38),   # Dmaj9
    ([47, 54, 57, 61, 62], [59, 62, 66, 69, 73, 69, 66, 62], 35),   # Bm9
    ([43, 50, 54, 57, 62], [55, 59, 62, 66, 69, 66, 62, 59], 31),   # Gmaj9
    ([45, 52, 57, 59, 64], [57, 62, 64, 69, 71, 69, 64, 62], 33),   # Asus4
]


def section_gain(t, points):
    """Piecewise-linear automation: points = [(time, value), ...]."""
    ts, vs = zip(*points)
    return np.interp(t, ts, vs)


def saw(phase, harmonics=9):
    out = np.zeros_like(phase)
    for k in range(1, harmonics + 1):
        out += np.sin(phase * k) / k * (0.85 ** (k - 1))
    return out


def lowpass(x, cutoff):
    """One-pole low pass (vectorised by blocks would be faster; fine for 2 min)."""
    a = np.exp(-2 * np.pi * cutoff / SR)
    y = np.empty_like(x)
    acc = 0.0
    for i in range(0, len(x), 4096):
        blk = x[i:i + 4096]
        out = np.empty_like(blk)
        for j, v in enumerate(blk):
            acc = (1 - a) * v + a * acc
            out[j] = acc
        y[i:i + 4096] = out
    return y


def pad():
    seg = 2 * BAR
    out_l = np.zeros(N)
    out_r = np.zeros(N)
    nseg = int(LENGTH / seg) + 1
    for s in range(nseg):
        notes, _arp, _bass = CHORDS[s % 4]
        start = s * seg - 0.4          # overlap for a soft crossfade
        a0, a1 = max(0, int(start * SR)), min(N, int((start + seg + 0.8) * SR))
        if a0 >= a1:
            continue
        tt = np.arange(a1 - a0) / SR
        env = np.minimum(1, tt / 0.9) * np.minimum(1, np.maximum(0, (seg + 0.8 - tt) / 0.9))
        for n in notes:
            f = midi(n)
            for det, pan in ((-0.11, 0.25), (0.13, 0.75)):
                ph = 2 * np.pi * f * (1 + det / 100) * tt + rng.uniform(0, 6.28)
                v = saw(ph, 7) * env * 0.05
                out_l[a0:a1] += v * (1 - pan)
                out_r[a0:a1] += v * pan
    return out_l, out_r


def arpeggio():
    step = BEAT / 2   # eighth notes
    out_l = np.zeros(N)
    out_r = np.zeros(N)
    nsteps = int(LENGTH / step)
    dur = 1.4
    tt = np.arange(int(dur * SR)) / SR
    for i in range(nsteps):
        t0 = i * step
        chord = CHORDS[int(t0 // (2 * BAR)) % 4]
        n = chord[1][i % 8] + 12
        f = midi(n)
        tone = (np.sin(2 * np.pi * f * tt) + 0.35 * np.sin(4 * np.pi * f * tt) * np.exp(-tt * 6)
                + 0.12 * np.sin(6 * np.pi * f * tt) * np.exp(-tt * 9))
        env = np.exp(-tt * 3.2) * np.minimum(1, tt / 0.004)
        v = tone * env * 0.06 * (1.0 if i % 2 == 0 else 0.75)
        a0 = int(t0 * SR)
        a1 = min(N, a0 + len(v))
        pan = 0.35 + 0.3 * ((i % 4) / 3)
        out_l[a0:a1] += v[:a1 - a0] * (1 - pan)
        out_r[a0:a1] += v[:a1 - a0] * pan
    return out_l, out_r


def bass():
    out = np.zeros(N)
    tt = np.arange(int(BEAT * SR)) / SR
    for b in range(int(LENGTH / BEAT)):
        t0 = b * BEAT
        root = CHORDS[int(t0 // (2 * BAR)) % 4][2]
        f = midi(root)
        env = np.minimum(1, tt / 0.01) * np.exp(-tt * 1.6)
        v = (np.sin(2 * np.pi * f * tt) + 0.25 * np.sin(4 * np.pi * f * tt)) * env * 0.16
        a0 = int(t0 * SR)
        a1 = min(N, a0 + len(v))
        out[a0:a1] += v[:a1 - a0]
    return out


def drums():
    kick = np.zeros(N)
    hat = np.zeros(N)
    kt = np.arange(int(0.45 * SR)) / SR
    freq = 45 + 85 * np.exp(-kt * 28)
    kphase = 2 * np.pi * np.cumsum(freq) / SR
    ksample = np.sin(kphase) * np.exp(-kt * 7.5) * 0.5
    ht = np.arange(int(0.09 * SR)) / SR
    noise = rng.standard_normal(len(ht))
    noise = noise - np.concatenate(([0], noise[:-1]))       # crude high pass
    hsample = noise * np.exp(-ht * 55) * 0.05
    for b in range(int(LENGTH / BEAT)):
        t0 = b * BEAT
        a0 = int(t0 * SR)
        a1 = min(N, a0 + len(ksample))
        kick[a0:a1] += ksample[:a1 - a0]
        h0 = int((t0 + BEAT / 2) * SR)
        h1 = min(N, h0 + len(hsample))
        if h0 < N:
            hat[h0:h1] += hsample[:h1 - h0]
    return kick, hat


def reverb(x, seconds=2.8, mix=0.32, seed=3):
    r = np.random.default_rng(seed)
    n = int(seconds * SR)
    tt = np.arange(n) / SR
    ir = r.standard_normal(n) * np.exp(-tt * 3.0 / seconds * 2.3)
    ir[: int(0.012 * SR)] = 0                                    # pre-delay
    ir /= np.sqrt(np.sum(ir ** 2))
    size = 1 << int(np.ceil(np.log2(len(x) + n)))
    wet = np.fft.irfft(np.fft.rfft(x, size) * np.fft.rfft(ir, size), size)[: len(x)]
    return x * (1 - mix) + wet * mix * 1.6


def main(path):
    # Arrangement (seconds): intro 0-7.5, build 7.5-30, main 30-95, lift 95-112.5, outro
    g_pad = section_gain(t_all, [(0, 0), (5, 1), (110, 1), (120, 0)])
    g_arp = section_gain(t_all, [(0, 0), (7.5, 0), (10, 0.7), (30, 1), (112.5, 1), (118, 0)])
    g_bass = section_gain(t_all, [(0, 0), (15, 0), (17.5, 1), (112.5, 1), (116, 0)])
    g_drum = section_gain(t_all, [(0, 0), (29.9, 0), (30, 1), (85, 1), (87.5, 0.35), (95, 0.35),
                                  (95.1, 1), (110, 1), (112.5, 0)])
    pl, pr = pad()
    al, ar = arpeggio()
    bs = bass()
    kick, hat = drums()
    pl = lowpass(pl, 2600)
    pr = lowpass(pr, 2600)
    left = pl * g_pad + al * g_arp + bs * g_bass + (kick + hat) * g_drum
    right = pr * g_pad + ar * g_arp + bs * g_bass + (kick + hat * 0.8) * g_drum
    left = reverb(left)
    right = reverb(right, seed=4)
    master = section_gain(t_all, [(0, 0), (1.5, 1), (116, 1), (120, 0)])
    stereo = np.stack([left * master, right * master], axis=1)
    stereo /= np.max(np.abs(stereo)) / 0.89                       # about -1 dBFS
    pcm = (stereo * 32767).astype("<i2")
    with wave.open(path, "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())
    print("wrote", path, f"{LENGTH:.0f} s")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "novaos-trailer-music.wav")
